namespace TodoApp.Domain.Common;

/// <summary>
/// Base class for Value Objects: things defined entirely by their attributes,
/// with no identity of their own. Two value objects with the same component
/// values ARE the same value object (unlike entities, which compare by Id).
///
/// Example candidate in this app: a "DueDate" or "Colour" — you don't care
/// WHICH DueDate instance you have, only what date it represents.
/// </summary>
public abstract class ValueObject
{
    protected abstract IEnumerable<object?> GetEqualityComponents();

    public override bool Equals(object? obj)
    {
        if (obj is null || obj.GetType() != GetType())
            return false;

        var other = (ValueObject)obj;
        return GetEqualityComponents().SequenceEqual(other.GetEqualityComponents());
    }

    public override int GetHashCode()
    {
        return GetEqualityComponents()
            .Select(x => x?.GetHashCode() ?? 0)
            .Aggregate((x, y) => x ^ y);
    }

    public static bool operator ==(ValueObject? left, ValueObject? right)
    {
        if (left is null && right is null) return true;
        if (left is null || right is null) return false;
        return left.Equals(right);
    }

    public static bool operator !=(ValueObject? left, ValueObject? right) => !(left == right);
}
